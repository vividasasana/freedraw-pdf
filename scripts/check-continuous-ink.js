const assert = require('node:assert/strict');
const {loadSource} = require('./load-source');
const ink = loadSource('src/ink/inkEngine.ts');
const {normalizeInkRenderSettings} = loadSource('src/settings/settingsController.ts');
const settings = {inkModel:'continuous-v1',strokeGeometry:'round',edgeGeometryVersion:2,widthSmoothing:'extra-smooth',widthSmoothingVersion:2,smoothingMode:'pressure',pressureResponse:'gentle',thinning:.5,streamline:.3,smoothing:.8,easing:'linear',taperStart:0,taperEnd:0,pressureMode:'stylus'};
const points = Array.from({length:80},(_,i)=>({x:.1+i*.009,y:.5+Math.sin(i*.15)*.09,pressure:.5+Math.sin(i*.12)*.35,t:i*8}));
const geometry = (p=points,options={}) => ink.getRoundedInkStrokeGeometry(p,1000,1400,8,true,false,{inkSettings:settings,...options});
const g = geometry();
assert.equal(g.samples[0].x,points[0].x*1000);
assert.equal(g.samples.at(-1).x,points.at(-1).x*1000);
assert.equal(g.samples.at(-1).y,points.at(-1).y*1400);
assert.equal(JSON.stringify(g),JSON.stringify(geometry(points.map(p=>({...p,t:p.t*20})))),'Writing speed/timestamps must not change pressure widths or geometry');
const live = ink.getRoundedInkStrokeGeometry(points,1000,1400,8,true,true,{inkSettings:settings,renderMode:'live',predictionStrength:1});
assert.equal(JSON.stringify(live),JSON.stringify(g),'Lifting the Pencil must not retract a synthetic tail or reshape the stroke');
const saved = geometry(points,{inkSettings:normalizeInkRenderSettings(JSON.parse(JSON.stringify(settings)))});
assert.equal(JSON.stringify(saved),JSON.stringify(g),'Save/reopen must preserve the exact pipeline');
const zoom = ink.getRoundedInkStrokeGeometry(points,4000,5600,32,true,false,{inkSettings:settings});
assert.equal(zoom.samples.length,g.samples.length);
zoom.samples.forEach((p,i)=>{assert.ok(Math.abs(p.x/4-g.samples[i].x)<1e-8);assert.ok(Math.abs(p.radius/4-g.samples[i].radius)<1e-8);});
const peakPoints=[.2,.4,1,.4,.2].map((pressure,i)=>({x:.1+i*.03,y:.5,pressure,t:i*8}));
const peak=geometry(peakPoints,{inkSettings:{...settings,streamline:0}});
assert.equal(Math.max(...peak.controlRadii),6,'Real pressure peaks must retain their full width');
assert.equal(Math.max(...peak.samples.map(p=>p.radius)),6,'Interpolating widths must not flatten or overshoot pressure peaks');
for(const p of peak.samples) assert.ok(p.radius>=2.8-1e-8 && p.radius<=6,'Pressure interpolation must remain bounded');
const neutral=geometry(points.map(p=>({...p,pressure:.5})));
assert.ok(neutral.samples.every(p=>Math.abs(p.radius-4)<1e-8),'Constant Pencil pressure must remain constant width');
const fast=geometry(points,{previewQuality:'fast'});
assert.ok(fast.samples.length<g.samples.length,'Fast preview must reduce curve work without dropping input');
assert.equal(JSON.stringify(fast.controlRadii),JSON.stringify(g.controlRadii));
const tiny=geometry([{x:.1,y:.1,pressure:.2},{x:.10001,y:.1,pressure:.8}]);
assert.ok(tiny.samples.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.radius)));
assert.equal(tiny.samples[0].radius,2.8,'Short strokes must retain their initial measured width');
const oldSettings={...settings};delete oldSettings.inkModel;
assert.equal(normalizeInkRenderSettings(oldSettings).inkModel,undefined,'Older strokes must not silently switch engines');
const {createRoundedInkPieces} = loadSource('src/ink/roundedInkGeometry.ts');
const expandedPieces=createRoundedInkPieces(g.samples);
assert.ok(g.pieces.length < expandedPieces.length*.6,'Compact tubes must reduce path pieces, not just add smoother geometry');
const {SvgDrawingContext} = loadSource('src/render/svgDrawingContext.ts');
const root={ownerDocument:{defaultView:{createFragment:()=>({createSvg:(_tag,options)=>({attrs:options.attr})})}}};
const svg=new SvgDrawingContext(root,100,100,new WeakMap());
svg.beginPath();svg.arc(0,0,10,-Math.PI/3,Math.PI/3,true);svg.fill();
const arcPath=svg.records[0].node.attrs.d;
assert.equal((arcPath.match(/ A /g)||[]).length,2,'SVG must subdivide the intended long anticlockwise arc');
assert.ok(arcPath.includes('-10'),'A long cap must pass through the back of its circle, matching Canvas');
console.log(`Continuous ink passed: endpoints, time independence, bounded pressure peaks, live/save/zoom parity, tiny strokes and compatibility. samples=${g.samples.length}; fast=${fast.samples.length}`);
